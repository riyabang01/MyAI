async function safeParseJson(response) {
  const text = await response.text();
  if (!text) return {};
  try {
    return JSON.parse(text);
  } catch {
    throw new Error(`Invalid response (${response.status}): ${text.slice(0, 120)}`);
  }
}

export async function pushProjectToGitHub(project) {
  const githubToken = process.env.GITHUB_TOKEN;
  if (!githubToken) {
    throw new Error('GITHUB_TOKEN missing in backend .env file');
  }

  const repoName = `${(project.name || 'mern-ai-project')
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40)}-${Date.now().toString().slice(-4)}`;

  const githubApiBase = 'https://github.com';

  const repoRes = await fetch(`${githubApiBase}/user/repos`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${githubToken}`,
      Accept: 'application/vnd.github+json',
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      name: repoName,
      description: project.prompt || 'Generated by MyAI MERN Builder',
      private: false,
      auto_init: true,
    }),
  });

  const repoData = await safeParseJson(repoRes);
  if (!repoRes.ok) {
    throw new Error(repoData.message || 'Failed to create GitHub repository');
  }

  const owner = repoData.owner.login;

  for (const file of project.files || []) {
    const cleanPath = file.path.replace(/^\/+/, '');
    if (!cleanPath) continue;

    const base64Content = Buffer.from(file.code || '', 'utf-8').toString('base64');

    const fileRes = await fetch(
      `${githubApiBase}/repos/${owner}/${repoName}/contents/${cleanPath}`,
      {
        method: 'PUT',
        headers: {
          Authorization: `Bearer ${githubToken}`,
          Accept: 'application/vnd.github+json',
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          message: `Add ${cleanPath}`,
          content: base64Content,
        }),
      }
    );

    if (!fileRes.ok) {
      const errData = await safeParseJson(fileRes);
      console.warn(`Failed to push ${cleanPath}:`, errData.message);
    }
  }

  return repoData.html_url;
}

export async function deployProjectToVercel(project) {
  const vercelToken = process.env.VERCEL_TOKEN;
  if (!vercelToken) {
    throw new Error('VERCEL_TOKEN missing in backend .env file');
  }

  const vercelFiles = (project.files || []).map((file) => ({
    file: file.path.replace(/^\/+/, ''),
    data: file.code || '',
  }));

  const hasClient = vercelFiles.some((f) => f.file.startsWith('client/'));
  const hasServer = vercelFiles.some((f) => f.file.startsWith('server/'));
  const serverEntry = vercelFiles.find(
    (f) => f.file === 'server/server.js' || f.file === 'server/index.js'
  );
  const hasVercelJson = vercelFiles.some((f) => f.file === 'vercel.json');

  let projectSettings = {
    framework: 'vite',
    buildCommand: 'npm run build',
    outputDirectory: 'dist',
    installCommand: 'npm install',
  };

  if (hasClient && hasServer && serverEntry) {
    projectSettings = {
      framework: null,
      buildCommand: 'cd client && npm install && npm run build',
      outputDirectory: 'client/dist',
      installCommand: 'cd server && npm install',
    };

    if (!hasVercelJson) {
      vercelFiles.push({
        file: 'vercel.json',
        data: JSON.stringify(
          {
            version: 2,
            builds: [
              { src: serverEntry.file, use: '@vercel/node' },
              {
                src: 'client/package.json',
                use: '@vercel/static-build',
                config: { distDir: 'dist' },
              },
            ],
            routes: [
              { src: '/api/(.*)', dest: `/${serverEntry.file}` },
              { handle: 'filesystem' },
              { src: '/(.*)', dest: '/client/dist/index.html' },
            ],
          },
          null,
          2
        ),
      });
    }
  } else {
    if (hasClient) {
      vercelFiles.forEach((f) => {
        if (f.file.startsWith('client/')) {
          f.file = f.file.replace(/^client\//, '');
        }
      });
    }

    const hasPackageJson = vercelFiles.some((f) => f.file === 'package.json');
    if (!hasPackageJson) {
      vercelFiles.push({
        file: 'package.json',
        data: JSON.stringify(
          {
            name: 'vite-react-app',
            private: true,
            version: '0.0.0',
            type: 'module',
            scripts: {
              dev: 'vite',
              build: 'vite build',
              preview: 'vite preview',
            },
            dependencies: {
              react: '^18.3.1',
              'react-dom': '^18.3.1',
              'lucide-react': '^0.460.0',
            },
            devDependencies: {
              '@vitejs/plugin-react': '^4.3.4',
              autoprefixer: '^10.4.20',
              postcss: '^8.4.49',
              tailwindcss: '^3.4.15',
              vite: '^6.0.1',
            },
          },
          null,
          2
        ),
      });
    }

    const hasViteConfig = vercelFiles.some(
      (f) => f.file === 'vite.config.js' || f.file === 'vite.config.ts'
    );
    if (!hasViteConfig) {
      vercelFiles.push({
        file: 'vite.config.js',
        data: `import { defineConfig } from 'vite'\nimport react from '@vitejs/plugin-react'\n\nexport default defineConfig({\n  plugins: [react()],\n})\n`,
      });
    }

    if (!hasVercelJson) {
      vercelFiles.push({
        file: 'vercel.json',
        data: JSON.stringify(
          {
            rewrites: [{ source: '/(.*)', destination: '/index.html' }],
          },
          null,
          2
        ),
      });
    }
  }

  const cleanName = (project.name || 'mern-ai-app')
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40) || 'mern-ai-app';

  const vercelDeployEndpoint = 'https://vercel.com';

  const response = await fetch(vercelDeployEndpoint, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${vercelToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      name: `${cleanName}-${Date.now().toString().slice(-4)}`,
      files: vercelFiles,
      target: 'production',
      projectSettings,
    }),
  });

  const data = await safeParseJson(response);
  if (!response.ok) {
    console.error('Vercel API Error:', JSON.stringify(data));
    throw new Error(data.error?.message || JSON.stringify(data.error) || 'Vercel deployment failed');
  }

  return `https://${data.url}`;
}
